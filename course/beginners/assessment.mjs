export function foundationAssessment(id,beginner) {
  const source=readFileSync(new URL('../../'+beginner.lessonPath,import.meta.url),'utf8');
  const section=source.split('## 在网页里完成三件小事')[1]?.split('\n## ')[0]||'';
  const questions=[...section.matchAll(/^\d+\. (.+)$/gm)].map(m=>m[1]);
  if(questions.length!==3 || data[id]?.length!==2) throw new Error('Missing foundation assessment '+id);
  return {
    checkpoints:questions.map((text,i)=>({id:'F'+(i+1),level:'foundation',title:'入门练习 '+(i+1),badge:'先完成',text,hint:'先只看本课最小例子。说明输入、变化和输出；不懂的术语回到字段来源表。'})),
    quiz:data[id].map(([question,correct,...rest],i)=>{
      const explanation=rest.pop(),options=[correct,...rest];
      const offset=(Number(id[1])+Number(id.slice(-2))+i)%4;
      return {id:'FQ'+(i+1),level:'foundation',question,options:[...options.slice(offset),...options.slice(0,offset)],answer:(4-offset)%4,explanation};
    }),
  };
}
